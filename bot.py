def giga_token():
    r = requests.post(OAUTH_URL,
        headers={"Authorization": "Basic " + GIGA_KEY,
                 "RqUID": str(uuid.uuid4()),
                 "Content-Type": "application/x-www-form-urlencoded"},
        data={"scope": "GIGACHAT_API_PERS"},
        timeout=20, verify=False)
    r.raise_for_status()
    return r.json()["access_token"]

def clean_text(text, token):
    parts = [text[i:i+4500] for i in range(0, len(text), 4500)]
    results = []
    for i, part in enumerate(parts, 1):
        header = PROMPT if len(parts) == 1 else PROMPT.replace(
            "Расшифровка:", f"Расшифровка (часть {i} из {len(parts)}; в конце части текст может обрываться - не обращай внимания):")
        r = requests.post(CHAT_URL,
            headers={"Authorization": "Bearer " + token,
                     "Content-Type": "application/json"},
            json={"model": "GigaChat",
                  "messages": [{"role": "user", "content": header + part}],
                  "max_tokens": 4000},
            timeout=180, verify=False)
        r.raise_for_status()
        results.append(r.json()["choices"][0]["message"]["content"])
    return "\n\n---\n\n".join(results)

def send(chat_id, text):
    for i in range(0, len(text), 3800):
        r = requests.post(f"{MAX_BASE}/messages?chat_id={chat_id}",
            headers=MAX_H, json={"text": text[i:i+3800]}, timeout=20)
        print("send ->", r.status_code, r.text[:200])

def main():
    state = pathlib.Path("state.txt")
    marker = state.read_text().strip() if state.exists() else ""
    params = {"limit": 100, "timeout": 0}
    if marker:
        params["marker"] = marker

    r = requests.get(f"{MAX_BASE}/updates", headers=MAX_H, params=params, timeout=30)
    r.raise_for_status()
    data = r.json()

    new_marker = str(data.get("marker", marker))
    pending = []

    for upd in data.get("updates", []):
        msg = upd.get("message")
        if not msg:
            continue
        body = msg.get("body", {})
        text = body.get("text", "").strip()
        if upd.get("update_type") != "message_created" or not text:
            continue
        if msg.get("sender", {}).get("is_bot"):
            continue
        if len(text) < MIN_LEN:
            send(msg["recipient"]["chat_id"],
                 "Пришлите расшифровку встречи текстом (не короче 50 символов), и я оформлю протокол.")
            continue
        pending.append((msg["recipient"]["chat_id"], text))

    if pending:
        print(f"Новых расшифровок: {len(pending)}")
        token = giga_token()
        for chat_id, text in pending:
            try:
                result = clean_text(text, token)
                send(chat_id, result)
            except Exception as e:
                print("ОШИБКА обработки:", e)
                send(chat_id, "Не смог обработать текст, попробуйте еще раз.")
    else:
        print("Новых сообщений нет.")

    state.write_text(new_marker, encoding="utf-8")

main()
